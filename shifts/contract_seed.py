def ensure_goz_2026_25_contract(*, WorkContract=None, WorkContractPosition=None, WorkPositionOperation=None) -> bool:
    """Создаёт контракт ГОЗ-2026-25, если его ещё нет. Возвращает True при создании."""
    if WorkContract is None or WorkContractPosition is None or WorkPositionOperation is None:
        from shifts.models import (
            WorkContract as WC,
            WorkContractPosition as WCP,
            WorkPositionOperation as WPO,
        )

        WorkContract = WorkContract or WC
        WorkContractPosition = WorkContractPosition or WCP
        WorkPositionOperation = WorkPositionOperation or WPO

    if WorkContract.objects.filter(name=GOZ_2026_25_NAME).exists():
        return False

    stage_not_started = getattr(WorkContractPosition, "STAGE_NOT_STARTED", "not_started")

    with transaction.atomic():
        sort = (
            WorkContract.objects.order_by("-sort_order").values_list("sort_order", flat=True).first()
            or 0
        ) + 1
        cab = WorkContract.objects.create(
            name=GOZ_2026_25_NAME,
            notes=GOZ_2026_25_NOTES,
            sort_order=sort,
        )
        for j, (name, desc, qty, ops) in enumerate(GOZ_2026_25_POSITIONS):
            pos = WorkContractPosition.objects.create(
                contract=cab,
                name=name,
                description=desc,
                quantity=qty,
                sort_order=j,
                stage=stage_not_started,
            )
            for k, op_name in enumerate(ops):
                WorkPositionOperation.objects.create(
                    position=pos, name=op_name, sort_order=k
                )
    return True
